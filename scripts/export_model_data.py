"""Write dsp/src/circuit/ModelData.inc from the prototype's model constants (single source of truth).

    source scripts/env.sh && $BLOCKAMP_PY scripts/export_model_data.py

The C++ netlist code includes the file inside `namespace magmora::model { ... }`. Never edit the output.
"""
import hashlib, json
from pathlib import Path
from blockamp import models, amp

out = Path(__file__).resolve().parent.parent / "dsp/src/circuit/ModelData.inc"
data = dict(T12AX7=models.T12AX7, P6L6GC=models.P6L6GC, D1N4007=models.D1N4007,
            PHYS={k: v for k, v in amp.PHYS.items() if not isinstance(v, str)}, DEFAULT_LOAD=amp.PHYS["load"])
h = hashlib.sha256(json.dumps(data, sort_keys=True).encode()).hexdigest()[:16]
L = ["// GENERATED by scripts/export_model_data.py from proto/blockamp/models.py and amp.PHYS. Do not edit.",
     "// Sources and confidence of every value: docs/research/CIRCUIT.md.",
     f'inline constexpr const char* kModelHash = "{h}";']
for name in ("T12AX7", "P6L6GC", "D1N4007", "PHYS"):
    L.append(f"struct {name}_t {{")
    L += [f"  double {k} = {float(v)!r};" for k, v in data[name].items()]
    L.append(f"}};\ninline constexpr {name}_t k{name}{{}};")
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(L) + "\n")
print("wrote", out, "hash", h)
