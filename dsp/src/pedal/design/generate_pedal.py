"""Generates dsp/src/pedal/PedalData.inc from the prototype (proto/blockamp/pedal.py: split, PHYS2, taper).

    source scripts/env.sh && PYTHONPATH=proto $BLOCKAMP_PY dsp/src/pedal/design/generate_pedal.py

The engine types no model constant: every element, value, device law and knob law comes from here. The four
clusters of split() are written in their full form, and O2 and O3 also in the cheap form of split(linear_opamps=
True) (same states, guard outputs vd and x). Knob-dependent resistors are written with their pot's total and law;
the engine evaluates them from the panel position. Capacitors named in pedal.PREWARP_CAPS are flagged."""
import hashlib
import sys
from pathlib import Path

from blockamp import pedal

OUT = Path(__file__).resolve().parents[1] / "PedalData.inc"
KNOB = {"Pdrive": 1, "Ptone_a": 2, "Ptone_b": 3, "Plevel_a": 4, "Plevel_b": 5}


def emit_cluster(tag, net):
    nodes = []
    def ix(n):
        if n == "0":
            return -1
        if n not in nodes:
            nodes.append(n)
        return nodes.index(n)
    els, states = [], []
    for e in net.elements:
        a, b = (ix(e.nodes[0]), ix(e.nodes[1]))
        knob = KNOB.get(e.name, 0)
        prewarp = 1 if (e.kind == "C" and e.name in pedal.PREWARP_CAPS) else 0
        inp = 1 if (e.kind == "V" and e.name in net.inputs) else 0
        if e.kind not in "RCVI":
            raise ValueError(f"{tag}: element kind {e.kind}")
        els.append(f'{{\'{e.kind}\', {a}, {b}, -1, -1, {e.value!r}, {knob}, {prewarp}, {inp}}}')
        if e.kind == "C":
            states.append(e.name)
    for name, a, b, cp, cn, gm in net.vccs:
        els.append(f"{{'G', {ix(a)}, {ix(b)}, {ix(cp)}, {ix(cn)}, {gm!r}, 0, 0, 0}}")
    devs = []
    for name, kind, ctrl, inj, par in net.devs:
        cn = [ix(n) for n, _ in ctrl] + [-1] * (3 - len(ctrl)); cc = [c for _, c in ctrl] + [0.0] * (3 - len(ctrl))
        jn = [ix(n) for n, _ in inj] + [-1] * (2 - len(inj)); jc = [c for _, c in inj] + [0.0] * (2 - len(inj))
        p = list(par[:4]) + [0.0] * (4 - len(par[:4]))
        devs.append("{%d, {%s}, {%s}, {%s}, {%s}, {%s}}" % (kind, ", ".join(map(str, cn)), ", ".join(map(repr, cc)),
                                                         ", ".join(map(str, jn)), ", ".join(map(repr, jc)), ", ".join(map(repr, p))))
    outs = []
    for name, a, b in net.outputs:
        outs.append(f"{{\"{name}\", {ix(a)}, {ix(b)}}}")
    return nodes, els, devs, outs, states


def main():
    ph = pedal.PHYS2
    # the engine implements these three knob laws (Pedal.cpp potOhms; PEDAL_SPEC 4)
    if (ph["drive_taper"], ph["tone_taper"], ph["level_taper"]) != ("audio15", "w", "audio"):
        sys.exit("knob laws changed: update potOhms in dsp/src/pedal/Pedal.cpp")
    full = pedal.split()
    cheap = pedal.split(linear_opamps=True)
    lines = ["// Generated by dsp/src/pedal/design/generate_pedal.py from proto/blockamp/pedal.py. Do not edit.", ""]
    body = []
    for variant, parts in (("full", full), ("cheap", cheap)):
        for k, (net, src, drive) in enumerate(parts):
            if variant == "cheap" and k in (0, 3):
                continue
            tag = f"{net.title}_{variant}"
            nodes, els, devs, outs, states = emit_cluster(tag, net)
            body.append((tag, nodes, els, devs, outs, states))
    # the cheap forms must carry exactly the states of the full ones
    st = {t: s for t, _, _, _, _, s in body}
    for c in ("O2", "O3"):
        if st[f"{c}_full"] != st[f"{c}_cheap"]:
            sys.exit(f"{c}: cheap and full states differ")
    for tag, nodes, els, devs, outs, states in body:
        lines.append(f"// {tag}: nodes {', '.join(nodes)}; states {', '.join(states)}")
        lines.append(f"inline constexpr PedalElement k{tag}Elements[] = {{\n  " + ",\n  ".join(els) + "};")
        if devs:
            lines.append(f"inline constexpr PedalDevice k{tag}Devices[] = {{\n  " + ",\n  ".join(devs) + "};")
        lines.append(f"inline constexpr PedalOutput k{tag}Outputs[] = {{" + ", ".join(outs) + "};")
        lines.append("")
    defs = []
    for tag, nodes, els, devs, outs, states in body:
        dv = f"k{tag}Devices, {len(devs)}" if devs else "nullptr, 0"
        defs.append(f'{{"{tag}", {len(nodes)}, k{tag}Elements, {len(els)}, {dv}, k{tag}Outputs, {len(outs)}}}')
    lines.append("// O1, O2, O3, O4 full, then O2 and O3 cheap")
    lines.append("inline constexpr PedalClusterDef kPedalClusters[] = {\n  " + ",\n  ".join(defs) + "};")
    lines.append("")
    lines.append(f"inline constexpr double kPedalDriveTotal = {ph['p_drive']!r}, kPedalDriveMid = {ph['drive_a_mid']!r};")
    lines.append(f"inline constexpr double kPedalToneTotal = {ph['p_tone']!r}, kPedalLevelTotal = {ph['p_level']!r};")
    lines.append(f"inline constexpr double kPedalTaperMid = {ph['taper_a_mid']!r}, kPedalPotMin = {ph['pot_rmin']!r};")
    lines.append(f"inline constexpr double kPedalPrewarpHz = {ph['prewarp_hz']!r}, kPedalBias = {ph['vbias']!r};")
    lines.append(f"inline constexpr double kPedalExpMax = {pedal.EXP_MAX!r};")
    text = "\n".join(lines) + "\n"
    digest = hashlib.sha256(text.encode()).hexdigest()[:16]
    text += f'inline constexpr const char* kPedalModelHash = "{digest}";\n'
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(body)} cluster forms, model {digest})")


if __name__ == "__main__":
    main()
