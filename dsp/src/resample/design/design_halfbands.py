"""Design the product's half-band and third-band FIRs and write ../HalfbandCoefficients.inc (our own design; scipy is a build-time
developer tool only).

    source scripts/env.sh && $BLOCKAMP_PY dsp/src/resample/design/design_halfbands.py

Linear phase: equiripple half-band by the Vaidyanathan-Nguyen trick (Remez on the non-zero branch), shortest length
with at least STOP_DB of stop-band rejection; because of the half-band symmetry the pass band is as flat.
Third-band (3x, polyphase): equiripple low-pass by Remez, length 3k+1 so that a round trip is a whole number of
samples at the lower rate, shortest with at least STOP_DB in the stop band and a pass band flat to PASS_RIPPLE_DB.
Minimum phase: the same magnitude response with every zero outside the unit circle reflected inside (exact, no
windowing or cepstral truncation).
"""
from pathlib import Path

import numpy as np
from scipy.signal import freqz, remez

STOP_DB = 110.0

# name, lowest rate it serves as the lower side of a stage, pass edge / upper rate, what for
DESIGNS = [
    ("First44", 0.0, 20000.0 / 88200.0, "first stage, hosts below 47 kHz: flat to 20 kHz"),
    ("First48", 47000.0, 20000.0 / 96000.0, "first stage, hosts of 47 to 86 kHz: flat to 20 kHz at 48 kHz"),
    ("First96", 86000.0, 0.16, "first stage, hosts of 86 to 172 kHz: flat to 28 kHz at 88.2 kHz"),
    ("First192", 172000.0, 0.085, "first stage, hosts from 172 kHz: flat to 30 kHz"),
    ("Inner96", 86000.0, 20000.0 / 176400.0, "inner stage from 88.2 / 96 kHz"),
    ("Inner192", 172000.0, 0.085, "inner stage from 176.4 / 192 kHz"),
    ("Inner384", 344000.0, 0.085 / 2.0, "inner stage from 352.8 / 384 kHz and above"),
]


PASS_RIPPLE_DB = 0.002

# name, lowest lower rate it serves, pass edge / upper rate, stop edge / upper rate, what for
THIRDS = [
    ("Third96", 86000.0, 28200.0 / 264600.0, 60000.0 / 264600.0,
     "3x from 88.2 / 96 kHz: flat to 28.2 kHz at 88.2 kHz; rejects the images of everything below 28.2 kHz"),
]


def third(n, fp, fs_):
    h = remez(n, [0.0, fp, fs_, 0.5], [1.0, 0.0], weight=[1.0, 40.0], fs=1.0, maxiter=200)
    return h / h.sum()


def third_ok(h, fp, fs_):
    f = np.linspace(fs_, 0.5, 8001)
    stop = -20.0 * np.log10(np.abs(freqz(h, worN=f, fs=1.0)[1]).max() + 1e-300)
    g = np.abs(freqz(h, worN=np.linspace(0.0, fp, 2001), fs=1.0)[1])
    ripple = 20.0 * np.log10(g.max() / g.min())
    return stop, ripple


def shortest_third(fp, fs_):
    n = 13
    while True:
        h = third(n, fp, fs_)
        stop, ripple = third_ok(h, fp, fs_)
        if stop >= STOP_DB and ripple <= PASS_RIPPLE_DB:
            return h, stop, ripple
        n += 3
        if n > 400:
            raise RuntimeError("specification not reachable")


def halfband(n, fp):
    g = remez((n + 1) // 2, [0.0, 2.0 * fp], [1.0], fs=1.0, maxiter=100)
    h = np.zeros(n)
    h[::2] = g / 2.0
    h[(n - 1) // 2] = 0.5
    return h


def stop_db(h, fp):
    f = np.linspace(0.5 - fp, 0.5, 8001)
    return -20.0 * np.log10(np.abs(freqz(h, worN=f, fs=1.0)[1]).max() + 1e-300)


def shortest(fp):
    n = 7
    while stop_db(halfband(n, fp), fp) < STOP_DB:
        n += 4
        if n > 255:
            raise RuntimeError("specification not reachable")
    return halfband(n, fp)


def minimum_phase(h):
    z = np.roots(h)
    outside = np.abs(z) > 1.0 + 1e-7
    gain = h[0] * np.prod(np.abs(z[outside]))
    z = np.where(outside, 1.0 / np.conj(z), z)
    # multiply the factors out on an FFT grid: stable where np.poly is not
    w = np.exp(-2j * np.pi * np.arange(1 << 13) / (1 << 13))
    H = np.full(len(w), gain, dtype=complex)
    for zk in z:
        H *= 1.0 - zk * w
    out = np.fft.ifft(H).real[: len(h)]
    out *= h.sum() / out.sum()                     # the same gain at DC, ripple included
    f = np.linspace(0.0, 0.5, 8001)
    error = np.abs(np.abs(freqz(out, worN=f, fs=1.0)[1]) - np.abs(freqz(h, worN=f, fs=1.0)[1])).max()
    if error > 1e-7:
        raise RuntimeError(f"minimum-phase magnitude differs by {error:.1e}")
    return out, error


def array(name, values):
    body = [f"  {float(v)!r}," for v in values]
    return [f"inline constexpr double {name}[] = {{", *body, "};"]


if __name__ == "__main__":
    L = ["// GENERATED by dsp/src/resample/design/design_halfbands.py. Do not edit.",
         "// Linear-phase entries list the even taps h[0], h[2], ... of a half-band (h[centre] = 0.5, the rest are zero).",
         ""]
    table = []
    for name, low_rate, fp, note in DESIGNS:
        h = shortest(fp)
        mh, error = minimum_phase(h)
        db = stop_db(h, fp)
        mdb = stop_db(mh, fp)
        print(f"{name:10s} taps {len(h):4d} delay {(len(h) - 1) // 2:3d} stop {db:6.1f} dB  minimum phase {mdb:6.1f} dB "
              f"magnitude error {error:.1e}")
        L.append(f"// {name}: {note}. {len(h)} taps, pass edge {fp:.5f}, stop band {db:.1f} dB.")
        L += array(f"k{name}Even", h[::2]) + array(f"k{name}Minimum", mh)
        table.append(f"  {{{float(low_rate)!r}, k{name}Even, k{name}Minimum, {len(h)}, {'true' if name.startswith('First') else 'false'}}},")
    L += ["inline constexpr HalfbandDesign kDesigns[] = {", *table, "};", ""]
    thirds = []
    for name, low_rate, fp, fs_, note in THIRDS:
        h, stop, ripple = shortest_third(fp, fs_)
        mh, error = minimum_phase(h)
        print(f"{name:10s} taps {len(h):4d} delay {(len(h) - 1) // 3:3d} (lower rate) stop {stop:6.1f} dB ripple {ripple:.4f} dB"
              f"  minimum phase magnitude error {error:.1e}")
        L.append(f"// {name}: {note}. {len(h)} taps, pass edge {fp:.5f}, stop edge {fs_:.5f}, stop band {stop:.1f} dB.")
        L += array(f"k{name}Linear", h) + array(f"k{name}Minimum", mh)
        thirds.append(f"  {{{float(low_rate)!r}, k{name}Linear, k{name}Minimum, {len(h)}}},")
    L += ["inline constexpr ThirdbandDesign kThirdDesigns[] = {", *thirds, "};"]
    out = Path(__file__).resolve().parent.parent / "HalfbandCoefficients.inc"
    out.write_text("\n".join(L) + "\n")
    print("wrote", out)
