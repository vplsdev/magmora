"""Export the partitioned prototype for bench/kernel_fast.cpp: a flat binary with the per-cluster matrices in the
layout the fast kernel uses, and a C++ header with the compile-time sizes and device lists.

usage: export_fast.py out.bin out_sizes.h [fs] [ctl-json] [--no-fold] [--no-minimal] [--modal]

What is done here (once per parameter set, i.e. what the product does at prepare()/rebuild time):
  * constant sources are folded into constant vectors (only the per-sample inputs stay as matrix columns);
  * each flyback diode is folded into the plate port of the pentode across the same node pair (exact);
  * the companion-state vector is reduced to a minimal realisation (exact: only directions that are never
    excited, or never seen by any output, are removed; these come from capacitor loops and parallel capacitors);
  * [Ss Sv Si; Ys Yv Yi] is stacked into one matrix W so that state update and outputs are one product.
"""
import json, struct, sys
import numpy as np
from blockamp.partition import PartSim, CLUSTERS_SPLIT

args = [a for a in sys.argv[1:] if not a.startswith("--")]
flags = {a for a in sys.argv[1:] if a.startswith("--")}
out, hdr = args[0], args[1]
fs = float(args[2]) if len(args) > 2 else 192000.0
ctl = json.loads(args[3]) if len(args) > 3 else None
FOLD, MINIMAL, MODAL = "--no-fold" not in flags, "--no-minimal" not in flags, "--modal" in flags
ps = PartSim(ctl, fs=fs, clusters=CLUSTERS_SPLIT)


def minimal(Ss, Bm, s0):
    """Remove the companion-state directions that can never be excited: left eigenvectors w of Ss with eigenvalue -1
    and w.B = 0, w.s0 = 0. They come from capacitor loops (the three inter-electrode capacitances of a tube, parallel
    capacitors): around such a loop sum(+-v_C) = 0, hence w = +-1/gc on the loop. They do not depend on any resistor,
    so the basis is computed once per sample rate, not per knob move. Returns T (orthonormal, ns x nr): s = T z, z = T' s."""
    ns = Ss.shape[0]
    U, sv, Vt = np.linalg.svd((Ss + np.eye(ns)).T)             # left null space of Ss + I
    Wn = Vt[sv < 1e-9 * sv[0]]                                 # rows: w with w (Ss + I) = 0
    if not len(Wn):
        return np.eye(ns)
    ok = np.linalg.norm(Wn @ Bm, axis=1) < 1e-9 * np.linalg.norm(Bm) and True if len(Wn) == 1 else None
    # keep only combinations that are neither driven nor initially excited
    D = np.hstack([Wn @ Bm / max(np.linalg.norm(Bm), 1e-300), (Wn @ s0)[:, None] / max(np.linalg.norm(s0), 1e-300)])
    U2, s2, _ = np.linalg.svd(D, full_matrices=True)
    r = int((s2 > 1e-9).sum())
    Wk = U2[:, r:].T @ Wn                                      # combinations with zero drive
    if not len(Wk):
        return np.eye(ns)
    _, s3, V3 = np.linalg.svd(Wk)
    return V3[len(Wk):].T                                      # orthonormal basis of null(Wk)


with open(out, "wb") as f, open(hdr, "w") as h:
    w_i = lambda *a: f.write(struct.pack(f"<{len(a)}q", *a))
    w_a = lambda a: f.write(np.ascontiguousarray(a, dtype="<f8").tobytes())
    nc = len(ps.cl)
    w_i(nc, ps.out_index[("P", "spk")][0], ps.out_index[("P", "spk")][1])
    h.write("// generated by bench/export_fast.py: compile-time cluster sizes and device lists\n")
    names = []
    for c in range(nc):
        L = ps.L
        g = lambda k: np.array(L[k][c], dtype=float)
        Pv, Ps_, K, Sv, Ss, Si, Yv, Ys, Yi = (g(k) for k in ("Pv", "Ps", "K", "Sv", "Ss", "Si", "Yv", "Ys", "Yi"))
        s0, v0, vdc, y0 = g("s"), g("v"), g("vdc"), g("ylast")
        dtype = [int(x) for x in ps.dev_type[c]]; dport = [int(x) for x in ps.dev_port[c]]
        par = np.zeros((len(dtype), 16)); par[:, :12] = np.array(ps.dev_par[c]).reshape(len(dtype), 12)
        # --- fold diodes into the pentode plate port that sits across the same node pair (K column = minus plate column)
        if FOLD:
            keep = list(range(K.shape[0])); nd_keep = []
            for d, t in enumerate(dtype):
                if t != 2: nd_keep.append(d); continue
                q = dport[d]; host = None
                for e, te in enumerate(dtype):
                    if te == 1 and np.allclose(K[:, dport[e]], -K[:, q], rtol=1e-12, atol=0) and np.allclose(Pv[dport[e]], -Pv[q]):
                        host = e
                if host is None: nd_keep.append(d); continue
                par[host, 12:15] = par[d, :3]; par[host, 15] = 1.0
                keep.remove(q)
            if len(keep) != K.shape[0]:
                old = dport
                remap = {o: n for n, o in enumerate(keep)}
                K = K[np.ix_(keep, keep)]; Pv = Pv[keep]; Ps_ = Ps_[keep]; Si = Si[:, keep]; Yi = Yi[:, keep]; v0 = v0[keep]
                dtype = [dtype[d] for d in nd_keep]; dport = [remap[old[d]] for d in nd_keep]; par = par[nd_keep]
        # --- constants and per-sample inputs
        idx = [int(x) for x in ps.in_idx[c]]
        const = [k for k in range(len(vdc)) if k not in idx]
        uc = vdc.copy(); uc[idx] = 0.0
        Pc, Sc, Yc = Pv @ uc, Sv @ uc, Yv @ uc
        Pu, Su, Yu = Pv[:, idx], Sv[:, idx], Yv[:, idx]
        u0 = vdc[idx]
        # --- minimal realisation of the companion states
        ns_full = Ss.shape[0]
        if MINIMAL and ns_full:
            T = minimal(Ss, np.hstack([Su, Si, Sc[:, None]]), s0); Lm = T.T
            Ss, Su, Si, Sc, s0 = Lm @ Ss @ T, Lm @ Su, Lm @ Si, Lm @ Sc, Lm @ s0
            Ps_, Ys = Ps_ @ T, Ys @ T
        if MODAL and Ss.shape[0]:
            # real block-diagonal (modal) form: z' = D z + ..., D with 1x1 and 2x2 blocks; stored dense here, the kernel
            # variant that exploits it reads the same file. Conditioning of the eigenvector matrix is printed.
            ev, V = np.linalg.eig(Ss)
            cols = []; k = 0
            order = np.argsort(-np.abs(ev.imag) * 0 + np.arange(len(ev)))
            used = np.zeros(len(ev), bool)
            for k in range(len(ev)):
                if used[k]: continue
                if abs(ev[k].imag) < 1e-12 * max(1.0, abs(ev[k])):
                    cols.append(V[:, k].real); used[k] = True
                else:
                    j = [m for m in range(len(ev)) if not used[m] and m != k and abs(ev[m] - ev[k].conj()) < 1e-9][0]
                    cols.append(V[:, k].real); cols.append(V[:, k].imag); used[k] = used[j] = True
            Vr = np.array(cols).T; Vr /= np.linalg.norm(Vr, axis=0)
            Vi = np.linalg.inv(Vr)
            print(f"  cluster {ps.cl[c]['name']}: modal basis condition {np.linalg.cond(Vr):.2e}")
            Ss, Su, Si, Sc, s0 = Vi @ Ss @ Vr, Vi @ Su, Vi @ Si, Vi @ Sc, Vi @ s0
            Ss[np.abs(Ss) < 1e-13 * np.abs(Ss).max()] = 0.0
            Ps_, Ys = Ps_ @ Vr, Ys @ Vr
        npo, ns, nin, ny, nd = K.shape[0], Ss.shape[0], len(idx), Yu.shape[0], len(dtype)
        W = np.block([[Ss, Su, Si], [Ys, Yu, Yi]]); Wc = np.concatenate([Sc, Yc])
        w_i(npo, ns, nin, ny, nd, int(ps.extrap[c]))
        for a in (Pc, Ps_, Pu, K, W, Wc, s0, v0, u0, y0):
            w_a(a)
        w_i(*dtype); w_i(*dport); w_a(par)
        w_i(*[int(x) for x in ps.in_src[c].ravel()]); w_a(ps.in_scale[c])
        nm = "L" + ps.cl[c]["name"]; names.append(nm)
        arr = lambda a: "{" + ", ".join(str(x) for x in (a if len(a) else [0])) + "}"
        h.write(f"struct {nm} {{ static constexpr int NP = {npo}, NS = {ns}, NIN = {nin}, NY = {ny}, ND = {nd};\n"
                f"  static constexpr int dtype[] = {arr(dtype)}; static constexpr int dport[] = {arr(dport)}; }};\n")
        print(f"  cluster {ps.cl[c]['name']}: ports {npo} states {ns_full} -> {ns} inputs {nin} outputs {ny} devices {nd}")
    h.write("#define CLUSTER_LIST(X) " + " ".join(f"X({k}, {n})" for k, n in enumerate(names)) + "\n")
    h.write(f"#define NCLUSTERS {nc}\n")
print("exported", nc, "clusters at", fs)
