#!/usr/bin/env python3
"""Write plugin/generated from the sources that own the data. build_mac.sh runs this before every build.

    generate.py            rewrite what is out of date
    generate.py --check    exit 1 if anything is out of date (nothing is written)

  Layout.inc    from plugin/resources/img/layout.json, the art package's contract
  PageLayout.inc from plugin/resources/img/pages.json, the contract of the block pages (pedal, EQ, cabinet)
  Presets.inc   from presets/*.json, in file name order, checked against Params.h and ChainParams.h
  Resources.rc  from plugin/resources/img and fonts (Windows links the assets into the binary)

BuiltinCab.inc and BuiltinCab.json (the built-in cabinet) are not made here: proto/cab/make_builtin_pack.py
writes them from the model. Here only the first preset is checked against the defaults they imply (cab_on).

The output is committed, because the Visual Studio project has no step that runs this.
"""
import json
import pathlib
import re
import sys

PLUGIN = pathlib.Path(__file__).resolve().parent.parent
ROOT = PLUGIN.parent
OUT = PLUGIN / "generated"
BANNER = "// Generated by plugin/scripts/generate.py from {}. Do not edit.\n"
KINDS = {"knob": "Knob", "button": "Switch", "toggle": "Switch", "rocker": "Switch", "glow": "Glow",
         "knob_light": "Static"}
# Settings that belong to the player and the session. A preset never carries them. The transposer's two (added
# 2026-11-24) are the player's like the input trim: loading a preset keeps the tuning you play in.
SESSION_KEYS = {"input_trim", "load", "quality", "phase_mode", "channel_mode", "transpose", "transpose_mode"}
PARAM = re.compile(r'\{\s*(?:ParamId\()?k\w+\)?,\s*"(\w+)",\s*"[^"]*",\s*"[^"]*",\s*([-\d.]+),\s*([-\d.]+),\s*([-\d.]+),'
                   r'\s*[\d.]+,\s*Taper::(\w+)')
# Per-block preset objects (dsp/src/chain/Chain.cpp kSections): key, then ranges of parameter keys (first, last).
# XP10's series response file ("user_ir") is gone since A22 (D42): a file is a cabinet slot's source, so a preset
# has no "user_ir" object.
BLOCKS = [("pedal", [("pedal_on", "pedal_level")]), ("eq", [("eq_on", "eq_b4_type")]),
          ("cab", [("cab_on", "mic_offset"), ("mic1_source", "mic2_source")]), ("fx", [("fx_on", "fx_on")])]
# Kept in the table for old sessions, without meaning (Chain::parameterHidden): never in a preset.
HIDDEN_KEYS = {"cab_floor", "user_ir_on", "user_ir_level"}
# Chain parameters that a preset carries in "params", with the head's: the head's own on/off (A32, Chain.cpp
# kSections "amp "). Like the head's preset parameters, every preset sets them (absent: their defaults).
HEAD_CHAIN_KEYS = ["amp_on"]


def fail(where, why):
    sys.exit(f"generate.py: {where}: {why}")


def params():
    """Head parameters (Params.h) then the chain's (ChainParams.h): one id space, as Chain uses."""
    found = []
    for name in ("Params.h", "ChainParams.h"):
        rows = [(key, float(lo), float(hi), float(default), taper == "Stepped") for key, lo, hi, default, taper
                in PARAM.findall((ROOT / "dsp/include/magmora" / name).read_text())]
        if not rows:
            fail(name, "no parameters recognised")
        found += rows
    return found


HEAD_COUNT = 22  # kNumParams; checked below against Params.h


def number(value):
    return f"{float(value)}f"


def quoted(text):
    if not isinstance(text, str) or not text.isascii() or not text.isprintable() or '"' in text or "\\" in text:
        fail("generated string", f"{text!r} is not plain ASCII")
    return f'"{text}"'


def layout(table):
    d = json.loads((PLUGIN / "resources/img/layout.json").read_text())
    if d.get("version") != 2:
        fail("layout.json", "version 2 is the one the UI implements")
    index = {key: i for i, (key, *_) in enumerate(table)}
    canvas, bar, bg, assets = d["canvas"], d["bar"], d["background"], d["assets"]
    rows = []
    for c in d["controls"]:
        where = f"layout.json, {c['id']}"
        if c["type"] not in KINDS:
            fail(where, f"unknown type {c['type']}")
        kind = KINDS[c["type"]]
        key = c.get("source") if kind == "Glow" else c["id"]
        if kind != "Static" and key not in index:
            fail(where, f"{key} is not a parameter")
        requires = c.get("requires")
        if requires is not None and requires not in index:
            fail(where, f"{requires} is not a parameter")
        if c.get("blend", "over") not in ("over", "add"):
            fail(where, "blend is over or add")
        if not 0 <= c.get("frame", 0) < c["frames"]:
            fail(where, "frame is outside the atlas")
        w, h, cols, frames = c["w"], c["h"], c["columns"], c["frames"]
        if any(v != int(v) for v in (w, h)):
            fail(where, "cell sizes must be whole points")
        asset = assets[c["asset"]]
        if (asset["w"], asset["h"]) != (w * cols, h * c["rows"]) or not 1 <= frames <= cols * c["rows"]:
            fail(where, "atlas size, cells and frame count disagree")
        values = [f"Kind::{kind}", quoted(c["id"]), str(index.get(key, -1)), quoted(asset["file"])]
        values += [number(v) for v in (c["x"], c["y"], w, h, c["hit"][0], c["hit"][1])]
        values += [str(frames), str(cols), str(c.get("frame", 0)), number(c.get("on_value", 0))]
        values += [str(index.get(requires, -1)), "true" if c.get("blend") == "add" else "false"]
        rows.append("  {" + ", ".join(values) + "},\n")
    colour = bar["colour"].lstrip("#")
    if not re.fullmatch(r"[0-9a-fA-F]{6}", colour):
        fail("layout.json", "bar.colour must be #rrggbb")
    return "".join([
        BANNER.format("plugin/resources/img/layout.json"),
        f"constexpr float kCanvasW = {number(canvas['w'])}, kCanvasH = {number(canvas['h'])};\n",
        f"constexpr Box kBar = {{{', '.join(number(bar[k]) for k in 'xywh')}}};\n",
        f"constexpr int kBarColour = 0x{colour.lower()};\n",
        f"constexpr Box kBackground = {{{', '.join(number(bg[k]) for k in 'xywh')}}};\n",
        f"constexpr const char* kBackgroundFile = {quoted(assets[bg['asset']]['file'])};\n",
        "constexpr Element kElements[] = {\n", *rows, "};\n",
    ])


PAGE_KINDS = {"knob": "Knob", "selector": "Selector", "switch": "Switch", "action": "Action", "lamp": "Lamp",
              "window": "Window"}


def pages(table):
    d = json.loads((PLUGIN / "resources/img/pages.json").read_text())
    if d.get("version") != 1:
        fail("pages.json", "version 1 is the one the UI implements")
    index = {key: i for i, (key, *_) in enumerate(table)}
    out = [BANNER.format("plugin/resources/img/pages.json")]
    names = []
    for name in d["order"]:
        page = d["pages"][name]
        assets = page["assets"]
        rows, colours = [], []
        for c in page["controls"]:
            where = f"pages.json, {name}, {c['id']}"
            if c.get("colours"):
                order = ("hp", "b1", "b2", "b3", "b4", "lp")
                colours.append("constexpr float kEqColours[6][3] = {" + ", ".join(
                    "{" + ", ".join(number(v) for v in c["colours"][k]) + "}" for k in order) + "};\n")
            kind = PAGE_KINDS.get(c["kind"])
            if kind is None:
                fail(where, f"unknown kind {c['kind']}")
            param = index.get(c["id"], -1)
            if kind in ("Knob", "Selector", "Switch") and param < 0 and not c.get("disabled"):
                fail(where, "not a parameter")
            source = c.get("source", "")
            if kind == "Window":
                values = [f"Kind::{kind}", quoted(c["id"]), "-1", quoted(""), *map(number, (c["x"], c["y"], c["w"], c["h"], 0, 0)),
                          "0", "1", "-1", quoted(""), number(0), "false", "{}", "0"]
            else:
                a = assets[c["asset"]]
                w, h = c["w"], c["h"]
                if any(v != int(v) for v in (w, h, c["x"] - w / 2, c["y"] - h / 2)):
                    fail(where, "cells must start on whole points")
                det = c.get("detents", [])
                values = [f"Kind::{kind}", quoted(c["id"]), str(param), quoted(a["file"]),
                          *map(number, (c["x"], c["y"], w, h, c.get("hit", [0, 0])[0], c.get("hit", [0, 0])[1])),
                          str(c["frames"]), str(c["columns"]), str(index.get(source, -1)), quoted(source),
                          number(c.get("on_value", 1)), "true" if c.get("disabled") else "false",
                          "{" + ", ".join(str(v) for v in det) + "}", str(len(det))]
            rows.append("  {" + ", ".join(values) + "},\n")
        ident = name.capitalize()
        glass = [a for a in assets.values() if a.get("window")]
        if glass:
            colours.append(f"constexpr const char* k{ident}GlassFile = {quoted(glass[0]['file'])};\n")
        out += [f"constexpr Control k{ident}Controls[] = {{\n", *rows, "};\n", *colours]
        names.append((name, ident, page["title"], page["background"]))
    out.append("constexpr Page kPages[] = {\n")
    for name, ident, title, bg in names:
        out.append(f"  {{{quoted(name)}, {quoted(title)}, {quoted(bg)}, k{ident}Controls, "
                   f"static_cast<int>(sizeof(k{ident}Controls) / sizeof(Control))}},\n")
    out.append("};\n")
    return "".join(out)


def plugin_defaults(table):
    """What a new instance of the plug-in starts with: the chain's defaults, except that the cabinet is on while the
    plug-in has its built-in cabinet (plugin/BuiltinCab.h, MAGMORA_BUILTIN_CAB)."""
    values = [default for _, _, _, default, _ in table]
    header = PLUGIN / "BuiltinCab.h"
    m = re.search(r"#define\s+MAGMORA_BUILTIN_CAB\s+(\d+)", header.read_text()) if header.exists() else None
    if m and int(m.group(1)):
        values[[key for key, *_ in table].index("cab_on")] = 1.0
    return values


def presets(table):
    index = {key: i for i, (key, *_) in enumerate(table)}
    head = len(PARAM.findall((ROOT / "dsp/include/magmora/Params.h").read_text()))
    if head != HEAD_COUNT:
        fail("Params.h", f"{head} head parameters, expected {HEAD_COUNT}")
    blocks = {name: [i for first, last in spans for i in range(index[first], index[last] + 1)] for name, spans in BLOCKS}
    head_ids = list(range(HEAD_COUNT)) + [index[key] for key in HEAD_CHAIN_KEYS]
    names, rows = set(), []
    for path in sorted((ROOT / "presets").glob("*.json")):
        where = f"presets/{path.name}"
        d = json.loads(path.read_text())
        name, category = d["name"], d["category"]
        # Hosts copy the name into fixed buffers; AU state restore has 64 bytes for it.
        if not 1 <= len(name) <= 31 or name in names:
            fail(where, "names are unique and at most 31 characters")
        names.add(name)
        values = [default for _, _, _, default, _ in table]
        # Which parameters the preset sets (Chain::applyPreset): the head's preset parameters always, a block's
        # parameters only if the preset has that block's object (absent keys at their defaults).
        given = [(i < HEAD_COUNT and key not in SESSION_KEYS) or key in HEAD_CHAIN_KEYS
                 for i, (key, *_) in enumerate(table)]
        objects = [("params", head_ids)] + [(name, blocks[name]) for name, _ in BLOCKS if name in d]
        for member in d:
            if member not in ("name", "category", "params") and member not in blocks:
                fail(where, f"unknown block object {member!r}")
        for block, ids in objects:
            for i in ids:
                given[i] = given[i] or (block != "params" and table[i][0] not in HIDDEN_KEYS)
            for key, value in d.get(block, {}).items():
                if key not in index or index[key] not in ids or key in SESSION_KEYS or key in HIDDEN_KEYS:
                    fail(where, f"{key} is not a preset parameter of {block!r}")
                _, lo, hi, _, stepped = table[index[key]]
                if isinstance(value, bool):
                    value = 1.0 if value else 0.0
                if not lo <= value <= hi or (stepped and value != int(value)):
                    fail(where, f"{key} = {value} is out of range")
                values[index[key]] = float(value)
        if not rows and values != plugin_defaults(table):
            fail(where, "the first preset is what a new instance shows, so it must equal the plug-in's defaults")
        rows.append(f"  {{{quoted(name)}, {quoted(category)},\n   {{{', '.join(str(v) for v in values)}}},\n"
                    f"   {{{', '.join('true' if g else 'false' for g in given)}}}}},\n")
    if not rows:
        fail("presets", "none found")
    session = ", ".join(str(index[key]) for key in sorted(SESSION_KEYS, key=index.get))
    return "".join([
        BANNER.format("presets/*.json"),
        f"constexpr int kSessionParams[] = {{{session}}};\n",
        f"constexpr int kNumGeneratedParams = {len(table)};\n",
        f"constexpr int kNumGeneratedHeadParams = {HEAD_COUNT};\n",
        "constexpr PresetDef kPresets[] = {\n", *rows, "};\n",
    ])


def resources():
    lines = [BANNER.format("plugin/resources/img and fonts")]
    types = {".png": "PNG", ".jpg": "JPG", ".ttf": "TTF"}
    for sub in ("img", "fonts"):
        folder = PLUGIN / "resources" / sub
        for f in sorted(folder.iterdir()):
            if f.suffix in types:
                # The quotes are part of the resource name: iPlug2's lookup strips one from each end.
                lines.append(f'"{f.name}" {types[f.suffix]} "..\\\\resources\\\\{sub}\\\\{f.name}"\n')
    return "".join(lines)


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] and not check:
        sys.exit(__doc__)
    table = params()
    files = {"Layout.inc": layout(table), "PageLayout.inc": pages(table), "Presets.inc": presets(table),
             "Resources.rc": resources()}
    stale = []
    for name, text in files.items():
        path = OUT / name
        if path.is_file() and path.read_text() == text:
            continue
        stale.append(name)
        if not check:
            OUT.mkdir(exist_ok=True)
            path.write_text(text)
    if check and stale:
        fail("plugin/generated", f"out of date: {', '.join(stale)}. Run plugin/scripts/generate.py")


if __name__ == "__main__":
    main()
