"""Write a Circuit as an ngspice deck using B-sources that mirror devices.py exactly."""
from .circuit import Circuit, GND
from .devices import PEN_EPS3, PEN_EPS1


def _sp(x):
    """Overflow-safe softplus as an ngspice expression. Below -30 it is written as exp(x) (equal to 4e-14 relative)
    so that it never evaluates to exactly zero: ngspice differentiates pwr(u, xi) symbolically and, for an exponent
    below one, would form inf * 0 at u = 0. devices.softplus returns 0 below -40; the difference is under 4e-18."""
    return f"(({x}) > 40 ? ({x}) : (({x}) < -30 ? exp(max({x},-700)) : ln(1+exp({x}))))"


def _triode_lines(e):
    p, g, k = e.nodes
    m = e.value
    n = e.name
    vpk, vgk = f"v({p},{k})", f"v({g},{k})"
    x = f"{m['kp']}*(1/{m['mu']}+({vgk}+{m['vct']})/sqrt({m['kvb']}+{vpk}*{vpk}))"
    e1 = f"(max({vpk},0)/{m['kp']}*{_sp(x)})"
    xg = f"{m['cg']}*({vgk}+{m['vg0']})"
    return [
        f"B{n}p {p} {k} I = 2/{m['kg1']}*pwr({e1},{m['ex']})",
        f"B{n}g {g} {k} I = {m['gg']}*pwr({_sp(xg)}/{m['cg']},{m['xi']})",
    ]


def _pentode_lines(e):
    p, s, g, k = e.nodes
    m = e.value
    n = e.name
    npar = e.extra.get("n_parallel", 1)
    vpk, vsk, vgk = f"v({p},{k})", f"max(v({s},{k}),1)", f"v({g},{k})"
    x = f"{m['kp']}*(1/{m['mu']}+{vgk}/{vsk})"
    i0 = f"(3.141592653589793/{m['kg1']}*pwr({vsk}/{m['kp']}*{_sp(x)},{m['ex']}))"
    vp = f"({_sp(f'4*{vpk}')}/4)"
    a = f"({m['kv']}*pwr({vp},1.5))"
    mm = f"({i0}*{a}*pwr(pwr({i0},3)+pwr({a},3)+{PEN_EPS3},-1/3))"
    xg = f"{m['cg']}*{vgk}"
    return [
        f"B{n}p {p} {k} I = {npar}*{mm}*(1+{m['lam']}*{vp})",
        f"B{n}s {s} {k} I = {npar}*{i0}*({m['rs']}+{m['asc']}*{i0}/({i0}+{a}+{PEN_EPS1}))",
        f"B{n}g {g} {k} I = {npar}*{m['gg']}*pwr({_sp(xg)}/{m['cg']},{m['xi']})",
    ]


def _diode_lines(e):
    a, k = e.nodes
    m = e.value
    v = f"v({a},{k})"
    ec = f"exp({m['vcrit']}/{m['nvt']})"
    return [f"B{e.name} {a} {k} I = {v} > {m['vcrit']} ? {m['isat']}*({ec}-1)+{m['isat']}*{ec}/{m['nvt']}*({v}-{m['vcrit']})"
            f" : {m['isat']}*(exp({v}/{m['nvt']})-1)"]


def export(c: Circuit, input_exprs=None, header=()):
    """Return deck text (no analysis cards). input_exprs maps input source name -> spice source spec."""
    input_exprs = input_exprs or {}
    low = {}
    for n in c.node_names():      # SPICE is case-insensitive: refuse netlists whose nodes would merge
        if n.lower() in ("eq", "ne", "gt", "lt", "ge", "le", "and", "or", "not"):
            raise ValueError(f"node name {n!r} is an operator in ngspice expressions")
        if low.setdefault(n.lower(), n) != n:
            raise ValueError(f"node names {n!r} and {low[n.lower()]!r} collide in SPICE")
    L = [f"* {c.title}", "* generated by proto/blockamp/spice.py -- do not edit", *header]
    from .dk import expand
    for e in expand(c):   # includes tube inter-electrode capacitors
        if e.kind in "RCL":
            L.append(f"{e.kind}{e.name} {e.nodes[0]} {e.nodes[1]} {e.value:.9g}")
        elif e.kind == "V":
            spec = input_exprs.get(e.name, f"dc {e.value:.9g}")
            L.append(f"V{e.name} {e.nodes[0]} {e.nodes[1]} {spec}")
        elif e.kind == "I":
            L.append(f"I{e.name} {e.nodes[0]} {e.nodes[1]} dc {e.value:.9g}")
        elif e.kind == "T":
            L += _triode_lines(e)
        elif e.kind == "P":
            L += _pentode_lines(e)
        elif e.kind == "D":
            L += _diode_lines(e)
        elif e.kind == "X":
            # ideal transformer referred to winding 0: v_k = (n_k/n_0) v_0 (VCVS in series with a 0 V
            # current probe), and winding 0 carries -sum((n_k/n_0) i_k) (CCCS), so power is conserved.
            turns = e.value
            a0, b0 = e.nodes[0], e.nodes[1]
            for k in range(1, len(turns)):
                a, b = e.nodes[2 * k], e.nodes[2 * k + 1]
                r = turns[k] / turns[0]
                L.append(f"V{e.name}s{k} {a} {e.name}_w{k} dc 0")
                L.append(f"E{e.name}w{k} {e.name}_w{k} {b} {a0} {b0} {r:.12g}")
                L.append(f"F{e.name}c{k} {b0} {a0} V{e.name}s{k} {r:.12g}")
        else:
            raise ValueError(e.kind)
    return "\n".join(L) + "\n"
